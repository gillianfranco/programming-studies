# Fatiamento de strings

s1 = 'Hello, World!'

print('Primeiro caractere: ' + s1[0]) # Primeira letra da string
print('Primeira palavra: ' + s1[0:5])
print('Último caractere: ' + s1[-1])
print('Última palavra: ' + s1[7:12])
print('Primeiros 3 caracteres: ' + s1[:3])
print('Últimos 3 caractere: ' + s1[-3:])