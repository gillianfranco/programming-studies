# Entrada de string

nome = input('Qual é o seu nome? ')
print(f'Seu nome é {nome}\n')

# Entrada de string e conversão para inteiro

idade = int(input('Qual é a sua idade? '))
print(f'Sua idade é {idade}\n')

# Entrada de string e conversão para float

altura = float(input('Qual a sua altura? '))
print(f'Sua altura é {altura}\n')
